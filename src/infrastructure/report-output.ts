import { invoke, isTauri } from "@tauri-apps/api/core";
import { z } from "zod";
import { familyReportIds } from "../../packages/domain/src/reports";
import { nativeCommands, type ReportPdfRequest, type ReportOutputResult } from "../bindings/native";

export type { ReportOutputResult } from "../bindings/native";
export const MAX_REPORT_PDF_BASE64 = 44_739_244;
const requestSchema = z.object({ reportId: z.enum(["RPT_Ordens_Reparacao", "RPT_Extrato_artigos", ...familyReportIds]),
  pdfBase64: z.string().min(1).max(MAX_REPORT_PDF_BASE64).regex(/^[A-Za-z0-9+/]+={0,2}$/).refine(value => value.length % 4 === 0),
}).strict();
const resultSchema = z.discriminatedUnion("kind", [z.object({ kind: z.literal("saved") }).strict(), z.object({ kind: z.literal("cancelled") }).strict(),
  z.object({ kind: z.literal("requested") }).strict(), z.object({ kind: z.literal("not_requested") }).strict()]);
export function nativeReportOutputAvailable(): boolean { return isTauri(); }

async function output(kind: "save" | "print", input: ReportPdfRequest): Promise<ReportOutputResult> {
  const request = requestSchema.parse(input);
  if (!isTauri()) throw new Error("native_only");
  const result = resultSchema.parse(await invoke<unknown>(kind === "save" ? nativeCommands.saveReportPdf : nativeCommands.printReportPdf, { request }));
  if (kind === "save" ? result.kind !== "saved" && result.kind !== "cancelled" : result.kind !== "requested" && result.kind !== "not_requested") throw new Error("invalid_report_output_result");
  return result;
}
/** Only the existing generated bytes and a report ID cross the native boundary. */
export function saveReportPdf(request: ReportPdfRequest): Promise<ReportOutputResult> { return output("save", request); }
export function printReportPdf(request: ReportPdfRequest): Promise<ReportOutputResult> { return output("print", request); }
