use serde::{Deserialize, Serialize};
use ts_rs::{Config, TS};

#[derive(Debug, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct NativeInfo {
    pub app_version: String,
    pub platform: String,
}

#[derive(Debug, Serialize, TS)]
pub struct StartupArguments {
    pub modulo: Option<String>,
    pub artigos: Option<String>,
}

#[derive(Debug, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct TerminalFolderRequest {
    pub initial_directory: String,
}

#[derive(Debug, Deserialize, TS)]
#[serde(deny_unknown_fields)]
pub struct RepairStateColorRequest {
    // A missing field is not an explicit nullable value at the IPC boundary.
    #[serde(deserialize_with = "deserialize_nullable_color")]
    pub color: Option<u32>,
}

fn deserialize_nullable_color<'de, D: serde::Deserializer<'de>>(
    deserializer: D,
) -> Result<Option<u32>, D::Error> {
    Option::<u32>::deserialize(deserializer)
}

#[derive(Debug, PartialEq, Serialize, TS)]
#[serde(tag = "kind", rename_all = "lowercase")]
pub enum RepairStateColorResult {
    Selected { color: u32 },
    Cancelled { color: Option<u32> },
}

#[derive(Debug, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ReportPdfRequest {
    pub report_id: String,
    pub pdf_base64: String,
}

#[derive(Debug, PartialEq, Serialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ReportOutputResult {
    Saved,
    Cancelled,
    Requested,
    NotRequested,
}

#[derive(Debug, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ScannerFileRequest {
    pub terminal_code: String,
    pub source_folder: String,
    pub source_filename: String,
}

#[derive(Debug, Serialize, TS)]
pub struct ScannerFileResult {
    pub text: String,
}

pub fn typescript_contract() -> String {
    format!(
        "// Generated by npm run bindings:generate. Do not edit.\n{}\n{}\n{}\n{}\n{}\n{}\n{}\n{}\n{}\nexport const nativeCommands = {{ nativeInfo: \"{}\", selectTerminalFolder: \"{}\", selectRepairStateColor: \"{}\", readStartupArguments: \"{}\", terminateApplication: \"{}\", saveReportPdf: \"{}\", printReportPdf: \"{}\", readTerminalScannerFile: \"{}\", playMessageSound: \"{}\" }} as const;\n",
        NativeInfo::export_to_string(&Config::default()).expect("NativeInfo must export"),
        TerminalFolderRequest::export_to_string(&Config::default())
            .expect("TerminalFolderRequest must export"),
        RepairStateColorRequest::export_to_string(&Config::default())
            .expect("RepairStateColorRequest must export"),
        RepairStateColorResult::export_to_string(&Config::default())
            .expect("RepairStateColorResult must export"),
        StartupArguments::export_to_string(&Config::default())
            .expect("StartupArguments must export"),
        ReportPdfRequest::export_to_string(&Config::default())
            .expect("ReportPdfRequest must export"),
        ReportOutputResult::export_to_string(&Config::default())
            .expect("ReportOutputResult must export"),
        ScannerFileRequest::export_to_string(&Config::default())
            .expect("ScannerFileRequest must export"),
        ScannerFileResult::export_to_string(&Config::default())
            .expect("ScannerFileResult must export"),
        crate::commands::NATIVE_INFO_COMMAND,
        crate::commands::SELECT_TERMINAL_FOLDER_COMMAND,
        crate::commands::SELECT_REPAIR_STATE_COLOR_COMMAND,
        crate::commands::READ_STARTUP_ARGUMENTS_COMMAND,
        crate::commands::TERMINATE_APPLICATION_COMMAND,
        crate::commands::SAVE_REPORT_PDF_COMMAND,
        crate::commands::PRINT_REPORT_PDF_COMMAND,
        crate::commands::READ_TERMINAL_SCANNER_FILE_COMMAND,
        crate::commands::PLAY_MESSAGE_SOUND_COMMAND
    )
}
